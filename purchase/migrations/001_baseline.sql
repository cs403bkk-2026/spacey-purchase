-- In production the platform creates this extension first; our role may not.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE spaces (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    capacity INTEGER NOT NULL,
    price_cents INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE bookings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id INTEGER NOT NULL REFERENCES spaces (id),
    member TEXT NOT NULL,
    user_id INTEGER REFERENCES users (id),  -- NULL for a guest booking
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    amount_cents INTEGER NOT NULL,
    status TEXT NOT NULL
        CHECK (status IN ('pending', 'completed', 'expired', 'cancelled')),
    card_last4 TEXT,  -- the only card data we keep
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- only pending and completed bookings hold a slot
    CONSTRAINT no_overlapping_bookings EXCLUDE USING gist (
        space_id WITH =, tstzrange(start_time, end_time) WITH &&
    ) WHERE (status IN ('pending', 'completed'))
);

-- Old rows kept as a record; no code reads this table.
CREATE TABLE subscriptions (
    member TEXT PRIMARY KEY,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    started_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
